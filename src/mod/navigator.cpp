// "PlayMenu" -> "Play menu". Uses the game's real class name; it is a
// stand-in until screens get proper titles from the text they draw.
std::wstring FriendlyClassName(const std::string& cls) {
    std::wstring out;
    for (size_t i = 0; i < cls.size(); ++i) {
        char c = cls[i];
        if (i > 0 && c >= 'A' && c <= 'Z' && !(cls[i - 1] >= 'A' && cls[i - 1] <= 'Z')) {
            out.push_back(L' ');
            out.push_back((wchar_t)(c - 'A' + 'a'));
        } else {
            out.push_back((wchar_t)c);
        }
    }
    return out;
}

// Logical area shown in the window (mouse remap rect), refreshed each tick.
// Starts empty: nothing counts as visible until the game's rect is read.
int g_visibleRect[4] = {0, 0, 0, 0};

// The game lays out its screens for the chosen art resolution (Normal,
// High, Ultra): logical space is as tall as the art (600, 768 or 1200).
// Every pixel distance below was measured at 768 and is scaled by this, so
// nothing depends on the art setting, window size or screen resolution.
double g_layoutScale = 1.0;
int Px(int at768) { return (int)(at768 * g_layoutScale + (at768 >= 0 ? 0.5 : -0.5)); }

// Text a player can see: drawn to the screen, not transparent, and inside
// the shown area (menus park their orbs and labels far off screen).
bool Visible(const DrawnText& t) {
    return t.onScreen && (t.color >> 24) >= 0x20 && t.x >= g_visibleRect[0] &&
           t.x < g_visibleRect[0] + g_visibleRect[2] && t.y >= g_visibleRect[1] &&
           t.y < g_visibleRect[1] + g_visibleRect[3];
}

// Text the game drew last frame inside a rectangle, in reading order.
// Fully transparent strings (fading tips) are not on screen, so skipped.
std::wstring DrawnTextIn(int x, int y, int w, int h) {
    std::wstring out;
    for (const DrawnText& t : TextCaptureInRect(x, y, w, h)) {
        if (!Visible(t)) continue;
        std::wstring s = CleanGameText(t.text);
        if (s.empty()) continue;
        if (!out.empty()) out += L" ";
        out += s;
    }
    return out;
}

bool Inside(int x, int y, const WidgetInfo& w) {
    return x >= w.absX && x < w.absX + w.width && y >= w.absY && y < w.absY + w.height;
}

// The caption the game draws beside a checkbox or slider: the nearest drawn
// string on the same row that is not drawn on another control. Options
// draws checkbox captions to the right of the box and slider captions to
// the left (runtime text dump 2026-10-30), so the preferred side is chosen
// by the caller. Empty if the game draws none.
std::wstring NearbyLabel(const WidgetInfo& c, const std::vector<WidgetInfo>& all,
                         const std::vector<DrawnText>& frame, bool preferRight) {
    const DrawnText* best = nullptr;
    int bestDistance = 0;
    for (const DrawnText& t : frame) {
        if (!Visible(t)) continue;
        // Baselines sit near the bottom of the text, so allow some slack.
        if (t.y < c.absY - Px(8) || t.y > c.absY + c.height + Px(12)) continue;
        bool onControl = false;
        for (const WidgetInfo& w : all)
            if (w.visible && (w.isButton || w.isEdit) && Inside(t.x, t.y, w)) onControl = true;
        if (onControl) continue;
        int distance;
        if (t.x < c.absX) distance = c.absX - t.x;
        else if (t.x >= c.absX + c.width) distance = t.x - (c.absX + c.width);
        else continue;
        bool right = t.x >= c.absX + c.width;
        if (right != preferRight) distance += Px(1000);  // other side only as a fallback
        if (distance > Px(1400)) continue;
        if (!best || distance < bestDistance) {
            best = &t;
            bestDistance = distance;
        }
    }
    return best ? CleanGameText(best->text) : L"";
}

// True if the game draws this button's label this frame, but only outside
// the visible screen. During the logo intro the main menu orbs exist at
// their final positions while their labels (and orbs) are drawn far below
// the screen as they fly in, so they are not really there yet.
bool LabelOnlyOffScreen(const WidgetInfo& w, const std::vector<DrawnText>& frame,
                        const int visibleRect[4]) {
    if (!w.labelRead) return false;
    std::wstring label = CleanGameText(w.label);
    if (label.empty()) return false;
    bool drawn = false;
    for (const DrawnText& t : frame) {
        if (!t.onScreen || CleanGameText(t.text) != label) continue;
        drawn = true;
        if (t.x >= visibleRect[0] && t.x < visibleRect[0] + visibleRect[2] &&
            t.y >= visibleRect[1] && t.y < visibleRect[1] + visibleRect[3])
            return false;
    }
    return drawn;
}

// Zen options sections (ZenCategoryContainer): container -> title, refreshed
// each tick from the game's own section data (docs/re/zen-options.md). The
// title is the string the game draws as the section heading.
std::vector<std::pair<uintptr_t, std::wstring>> g_sectionTitles;

// Title of the section a control sits in, or empty for controls placed
// directly on a dialog or screen.
std::wstring SectionTitle(const WidgetInfo& c, const std::vector<WidgetInfo>& all,
                          const std::vector<DrawnText>& frame) {
    if (c.parentIndex < 0) return L"";
    for (const auto& known : g_sectionTitles)
        if (known.first == all[c.parentIndex].ptr)
            return known.second == NearbyLabel(c, all, frame, true) ? L"" : known.second;
    return L"";
}

// Header items for the Zen options sections. The game selects (opens) a
// section when the mouse rests on its background, so focusing a header
// hovers it there and Enter does the same.
void AddZenSections(const zen::ZenOptionsState& zs, const std::vector<WidgetInfo>& all,
                    std::vector<Item>* items) {
    for (const zen::ZenSection& sec : zs.sections) {
        if (!sec.container) continue;
        int index = -1;
        for (int k = 0; k < (int)all.size(); ++k)
            if (all[k].ptr == sec.container) index = k;
        if (index < 0 || !all[index].visible) continue;
        const WidgetInfo& c = all[index];
        std::vector<controls::MouseStep> steps;
        zen::ExpandPlan plan = zen::PlanExpandSection(zs, sec.id, all, &steps);
        int px = c.absX + Px(20), py = c.absY + Px(20);
        if (plan == zen::ExpandPlan::Planned && !steps.empty()) {
            px = steps.front().x;
            py = steps.front().y;
        }
        Item it{c.ptr, ItemKind::Section, L"", px - 2, py - 2, 4, 4, px, py,
                false, false, L""};
        std::wstring title = CleanGameText(sec.title);
        bool open = zs.selected == sec.id;
        it.speech = (title.empty() ? L"unnamed" : title) + L", section" +
                    (open ? L", open" : L"") + (sec.enabled ? L"" : L", off");
        it.key = c.ptr;
        it.orderY = c.absY;  // the section's top edge: before its own controls
        std::wstring description;
        if (hover_text::ZenSectionDescription(sec.id, &description))
            it.description = CleanGameText(description);
        items->push_back(std::move(it));
    }
}


std::wstring ButtonText(const WidgetInfo& w) {
    std::wstring label = w.labelRead ? CleanGameText(w.label) : L"";
    if (!label.empty()) return label;
    // No label: the game's own resource name for the button's picture, e.g.
    // IMAGE_OVERWORLD_BACK_BUTTON -> "overworld back button". This comes
    // before drawn text because large picture buttons (quest orbs) overlap
    // text that belongs to the screen, such as its heading.
    std::wstring imageWords;
    if (ButtonImageWords(w.ptr, &imageWords)) return imageWords;
    // No picture either: whatever the game draws on the button itself (the
    // main menu's change-user area, string 288).
    std::wstring drawn = DrawnTextIn(w.absX, w.absY, w.width, w.height);
    if (!drawn.empty()) return drawn;
    // Nothing the game provides: say so honestly rather than guessing.
    return L"unlabeled " + FriendlyClassName(w.className) + L" " + std::to_wstring(w.buttonId);
}

// Builds the item for a widget, or returns false if it is not navigable.
bool MakeItem(const WidgetInfo& w, const std::vector<WidgetInfo>& all,
              const std::vector<DrawnText>& frame, const std::string& dialogClass, Item* out) {
    Item it{w.ptr, ItemKind::Button, L"", w.absX, w.absY, w.width, w.height,
            w.absX + w.width / 2, w.absY + w.height / 2, w.isOver, false, L""};
    controls::Kind kind = controls::Classify(w.ptr);
    std::wstring section = SectionTitle(w, all, frame);
    std::wstring prefix = section.empty() ? L"" : section + L", ";
    if (kind == controls::Kind::DropList) {
        controls::DropListState s;
        if (!controls::ReadDropList(w.ptr, &s)) return false;
        std::wstring label = NearbyLabel(w, all, frame, /*preferRight=*/false);
        std::wstring value;
        if (s.list && s.selected >= 0) controls::ReadListLine(s.list, s.selected, &value);
        value = CleanGameText(value);
        it.kind = ItemKind::DropList;
        it.caption = label;
        it.speech = prefix + (label.empty() ? L"unlabeled" : label) + L", drop-down, " +
                    (value.empty() ? std::wstring(L"nothing selected") : value) +
                    (s.open ? L", open" : L"");
    } else if (kind == controls::Kind::Checkbox) {
        controls::CheckboxState s;
        if (!controls::ReadCheckbox(w.ptr, &s)) return false;
        std::wstring label = NearbyLabel(w, all, frame, /*preferRight=*/true);
        bool radio = controls::IsRadioCheckbox(dialogClass, s.id);
        it.caption = label;
        it.kind = ItemKind::Checkbox;
        it.speech = prefix + (label.empty() ? L"unlabeled" : label) +
                    (radio ? (s.checked ? L", radio button, selected" : L", radio button, not selected")
                           : (s.checked ? L", checkbox, checked" : L", checkbox, not checked"));
    } else if (kind == controls::Kind::Slider) {
        controls::SliderState s;
        if (!controls::ReadSlider(w.ptr, &s)) return false;
        // A vertical slider (Zen options' panel scroller) has no caption
        // beside it; nearby text belongs to other controls.
        std::wstring label =
            s.horizontal ? NearbyLabel(w, all, frame, /*preferRight=*/false) : L"";
        it.kind = ItemKind::Slider;
        it.caption = label;
        // Vertical sliders are drawn with the top as the high end (Zen music
        // volume is shown as 1 - value), so report the share from the bottom.
        double shown = s.horizontal ? s.value : 1.0 - s.value;
        it.speech = prefix + (label.empty() ? L"unlabeled" : label) +
                    (s.horizontal ? L", slider, " : L", vertical slider, ") +
                    std::to_wstring(controls::SliderPercent(shown)) + L" percent";
    } else if (kind == controls::Kind::TabButton) {
        controls::TabButtonState s;
        if (!controls::ReadTabButton(w.ptr, &s)) return false;
        it.kind = ItemKind::Tab;
        it.selectedTab = s.selected;
        it.speech = ButtonText(w) + (s.selected ? L", tab, selected" : L", tab");
    } else if (w.className == "ScoreEntryWidget") {
        // A high-score table row: read-only, offered so the table can be read.
        controls::ScoreRow row;
        if (!controls::ReadScoreEntry(w.ptr, &row) || !row.present) return false;
        it.kind = ItemKind::ScoreRow;
        it.speech = std::to_wstring(row.rank) + L". " + CleanGameText(row.name) + L", " +
                    std::to_wstring(row.score);
    } else if (w.isEdit) {
        std::wstring text = CleanGameText(w.editText);
        it.kind = ItemKind::Edit;
        it.speech = L"edit, " + (text.empty() ? std::wstring(L"blank") : text);
    } else if (w.isButton) {
        it.speech = ButtonText(w);
        // Quest orbs: the quest's own name and description from the game's
        // quest data (docs/re/hover-text.md), not the orb's picture name.
        std::wstring questName, questText;
        if (w.className == "QuestMenuBtn" && w.parentIndex >= 0 &&
            hover_text::QuestOrbText(all[w.parentIndex].ptr, w.ptr, &questName, &questText)) {
            questName = CleanGameText(questName);
            if (!questName.empty()) it.speech = questName;
            it.description = CleanGameText(questText);
        }
    } else {
        return false;  // lists, drop lists and scrollbars: not wired up yet
    }
    *out = it;
    return true;
}

std::wstring DialogText(uintptr_t dialog) {
    std::wstring out, s;
    const int fields[] = {sexy::kDialogHeader, sexy::kDialogLines, sexy::kDialogFooter};
    for (int off : fields) {
        if (ReadWString(dialog + off, &s)) {
            s = CleanGameText(s);
            if (s.empty()) continue;
            if (!out.empty()) {
                wchar_t last = out.back();
                out += (last == L'.' || last == L'!' || last == L'?') ? L" " : L". ";
            }
            out += s;
        }
    }
    return out;
}

int FocusIndex() {
    for (size_t i = 0; i < g_items.size(); ++i)
        if (g_items[i].key == g_focus) return (int)i;
    return -1;
}

const Item* FocusedItem() {
    int i = FocusIndex();
    return i < 0 ? nullptr : &g_items[i];
}

void SpeakFocus(bool interrupt) {
    int i = FocusIndex();
    if (i < 0) return;
    Speak(g_items[i].speech + L", " + std::to_wstring(i + 1) + L" of " +
              std::to_wstring(g_items.size()), interrupt);
    if (!g_items[i].description.empty()) Speak(g_items[i].description, false);
}

// Reading order: rows top to bottom (centres within 16 logical px share a
// row), then left to right.
void SortReadingOrder(std::vector<Item>* items) {
    auto y = [](const Item& i) { return i.orderY != INT_MIN ? i.orderY : i.centerY; };
    std::stable_sort(items->begin(), items->end(), [&](const Item& a, const Item& b) {
        // Section headers sort by exact position, not by row band.
        if (a.orderY != INT_MIN || b.orderY != INT_MIN) return y(a) < y(b);
        if (std::abs(y(a) - y(b)) > Px(16)) return y(a) < y(b);
        return a.centerX < b.centerX;
    });
}

// Echoes typing in the game's focused edit field, since the game draws the
// text itself and the screen reader cannot see it.
void EchoEditChanges(uintptr_t wm, const std::vector<WidgetInfo>& all) {
    uintptr_t focus = GameFocusWidget(wm);
    const WidgetInfo* edit = nullptr;
    for (const WidgetInfo& w : all)
        if (w.ptr == focus && w.isEdit) edit = &w;
    if (!edit) {
        g_editPtr = 0;
        return;
    }
    if (edit->ptr != g_editPtr) {
        g_editPtr = edit->ptr;
        g_editText = edit->editText;
        return;
    }
    const std::wstring& now = edit->editText;
    if (now == g_editText) return;
    if (now.size() > g_editText.size() && now.compare(0, g_editText.size(), g_editText) == 0) {
        std::wstring added = now.substr(g_editText.size());
        Speak(added == L" " ? L"space" : added, true);
    } else if (now.size() < g_editText.size() &&
               g_editText.compare(0, now.size(), now) == 0) {
        std::wstring removed = g_editText.substr(now.size());
        Speak(L"deleted " + (removed == L" " ? std::wstring(L"space") : removed), true);
    } else {
        Speak(now.empty() ? L"blank" : now, true);
    }
    g_editText = now;
}

// Orders drawn strings for reading. Default is the game's draw order, which
// keeps side-by-side caption blocks intact (How to Play). Table layouts are
// read row by row instead: a left-aligned column of 3+ strings (same x,
// within 3 px) is a table, and each of its strings is read together with
// the strings on its row to the right (a stats label and its value, a
// high-score rank, name and score).
std::vector<std::wstring> ReadingOrder(const std::vector<DrawnText>& in) {
    // Drop exact repeats (some widgets draw the same string several times).
    std::vector<DrawnText> f;
    for (const DrawnText& t : in) {
        bool dup = false;
        for (const DrawnText& u : f)
            if (u.x == t.x && u.y == t.y && u.text == t.text) dup = true;
        if (!dup) f.push_back(t);
    }
    std::vector<int> tableOf(f.size(), -1);  // table id per fragment
    std::vector<std::vector<int>> tables;    // row-start fragments per table
    // Leftmost columns first, so a row starts at its first column (rank
    // "1." before name and score).
    std::vector<int> byX(f.size());
    for (size_t k = 0; k < f.size(); ++k) byX[k] = (int)k;
    std::stable_sort(byX.begin(), byX.end(), [&](int a, int b) { return f[a].x < f[b].x; });
    for (int i : byX) {
        if (tableOf[i] >= 0) continue;
        std::vector<int> column;
        for (size_t j = 0; j < f.size(); ++j)
            if (tableOf[j] < 0 && std::abs(f[j].x - f[i].x) <= Px(3)) column.push_back((int)j);
        if (column.size() < 3) continue;
        int id = (int)tables.size();
        std::sort(column.begin(), column.end(), [&](int a, int b) { return f[a].y < f[b].y; });
        tables.push_back(column);
        for (int start : column) {
            tableOf[start] = id;
            for (size_t j = 0; j < f.size(); ++j)
                if (tableOf[j] < 0 && std::abs(f[j].y - f[start].y) <= Px(4) && f[j].x > f[start].x)
                    tableOf[j] = id;
        }
    }
    std::vector<std::wstring> out;
    std::vector<bool> emitted(tables.size(), false);
    for (size_t i = 0; i < f.size(); ++i) {
        int id = tableOf[i];
        if (id < 0) {
            out.push_back(CleanGameText(f[i].text));
            continue;
        }
        if (emitted[id]) continue;
        emitted[id] = true;
        for (int start : tables[id]) {
            std::vector<int> row;
            for (size_t j = 0; j < f.size(); ++j)
                if (tableOf[j] == id && std::abs(f[j].y - f[start].y) <= Px(4) &&
                    f[j].x >= f[start].x)
                    row.push_back((int)j);
            std::sort(row.begin(), row.end(), [&](int a, int b) { return f[a].x < f[b].x; });
            std::wstring line;
            for (int k : row) {
                std::wstring s = CleanGameText(f[k].text);
                if (!s.empty()) line += (line.empty() ? L"" : L" ") + s;
            }
            if (!line.empty()) out.push_back(line);
        }
    }
    return out;
}

// Resource id words: "IMAGE_FLAME_GEM_ICON" -> "flame gem icon".
std::wstring ResourceWords(const std::string& id) {
    std::string name = id.compare(0, 6, "IMAGE_") == 0 ? id.substr(6) : id;
    std::wstring out;
    for (char c : name) out.push_back(c == '_' ? L' ' : (wchar_t)tolower((unsigned char)c));
    return out;
}

// What some dialogs show only as pictures or animation, read from the
// dialog's data (docs/re/rare-dialogs.md). Returns text to append.
std::wstring RareDialogDetails(uintptr_t dialog, const std::wstring& already) {
    std::wstring out;
    switch (dialog_text::ClassifyRareDialog(dialog)) {
        case dialog_text::RareDialog::RankUp: {
            dialog_text::RankUpInfo r;
            if (dialog_text::ReadRankUp(dialog, &r)) {
                std::wstring name = CleanGameText(r.rankName);
                if (!name.empty() && already.find(name) == std::wstring::npos) out += L". " + name;
            }
            break;
        }
        case dialog_text::RareDialog::BadgeAward: {
            dialog_text::BadgeAwardInfo b;
            if (dialog_text::ReadBadgeAward(dialog, &b) && b.indexKnown && b.shownIndex >= 0 &&
                b.shownIndex < (int)b.badges.size()) {
                const dialog_text::AwardedBadge& a = b.badges[b.shownIndex];
                out += L". " + CleanGameText(a.name) + L", " + CleanGameText(a.levelName);
            }
            break;
        }
        case dialog_text::RareDialog::EndLevel: {
            // Classic and Butterflies show special gem counts as icons
            // followed by "x N"; name each by its icon's resource id.
            std::vector<dialog_text::SpecialGemCount> gems;
            if (dialog_text::ReadEndLevelSpecialGems(dialog, &gems))
                for (const auto& g : gems)
                    if (g.countKnown && !g.imageName.empty())
                        out += L". " + ResourceWords(g.imageName) + L" " + std::to_wstring(g.count);
            break;
        }
        case dialog_text::RareDialog::ZenIntro: {
            // The intro is a single picture with no text; say its name.
            std::string image;
            if (dialog_text::ReadZenIntroImageName(&image)) out += L". picture: " + ResourceWords(image);
            break;
        }
        default:
            break;
    }
    return out;
}

// Dialog header/lines/footer plus what the dialog draws itself (e.g. the
// welcome dialog's prompt, string 511), minus text on its controls.
std::wstring DialogSpeech(const std::vector<WidgetInfo>& all, int dialogIndex) {
    const WidgetInfo& d = all[dialogIndex];
    std::wstring text = DialogText(d.ptr);
    // Keep the game's draw order: it draws each caption block in turn, which
    // reads correctly even for side-by-side columns (How to Play), unlike a
    // top-to-bottom sort. Dialogs draw their header first, so anything drawn
    // before this dialog's header belongs to what lies underneath (e.g. the
    // user list under NEW USER).
    std::vector<DrawnText> frame = TextCaptureLastFrame();
    std::wstring header;
    ReadWString(d.ptr + sexy::kDialogHeader, &header);
    header = CleanGameText(header);
    size_t start = 0;
    for (size_t k = frame.size(); !header.empty() && k-- > 0;) {
        if (CleanGameText(frame[k].text) == header) {
            start = k;
            break;
        }
    }
    std::vector<DrawnText> kept;
    for (size_t k = start; k < frame.size(); ++k) {
        const DrawnText& t = frame[k];
        if (!Visible(t) || t.x < d.absX || t.x >= d.absX + d.width || t.y < d.absY ||
            t.y >= d.absY + d.height)
            continue;
        std::wstring s = CleanGameText(t.text);
        if (s.empty() || text.find(s) != std::wstring::npos) continue;
        // List lines are read as list items.
        bool listLine = false;
        for (const Item& it : g_items)
            if (it.kind == ItemKind::ListRow && it.speech.compare(0, s.size(), s) == 0)
                listLine = true;
        if (listLine) continue;
        // Labels of buttons behind the dialog (the play orb under the quit dialog).
        bool behind = false;
        for (int i = 0; i < (int)all.size(); ++i) {
            if (IsWithin(all, i, dialogIndex) || !all[i].isButton || !all[i].labelRead) continue;
            if (CleanGameText(all[i].label) == s) behind = true;
        }
        if (behind) continue;
        // Control captions are read with their control, not in the intro.
        bool onItem = false;
        for (const Item& it : g_items)
            if (!it.caption.empty() && it.caption == s) onItem = true;
        for (int i = dialogIndex + 1; i < (int)all.size() && all[i].depth > d.depth; ++i) {
            const WidgetInfo& w = all[i];
            if ((w.isButton || w.isEdit) && w.visible && Inside(t.x, t.y, w)) onItem = true;
        }
        if (!onItem) kept.push_back(t);
    }
    for (const std::wstring& piece : ReadingOrder(kept))
        if (!piece.empty()) text += (text.empty() ? L"" : L" ") + piece;
    text += RareDialogDetails(d.ptr, text);
    return text;
}

// One item per list line the game currently draws. A row's position is
// where the game draws its text, so clicks land on that line.
void AddListRows(const WidgetInfo& w, const std::vector<DrawnText>& frame,
                 std::vector<Item>* items) {
    controls::ListState s;
    if (!controls::ReadList(w.ptr, &s)) return;
    for (int row = 0; row < s.count && row < 200; ++row) {
        std::wstring line;
        if (!controls::ReadListLine(w.ptr, row, &line)) continue;
        std::wstring clean = CleanGameText(line);
        const DrawnText* drawn = nullptr;
        for (const DrawnText& t : frame)
            if (Visible(t) && CleanGameText(t.text) == clean && t.x >= w.absX &&
                t.x < w.absX + w.width && t.y >= w.absY && t.y < w.absY + w.height + Px(16))
                drawn = &t;
        if (!drawn) continue;  // scrolled out of view
        // Baselines sit near the bottom of a line: centre the row 8 px above.
        int cy = drawn->y - Px(8);
        Item it{w.ptr, ItemKind::ListRow, L"", w.absX, cy - Px(12), w.width, Px(24),
                w.absX + w.width / 2, cy, s.hilite == row, false, L""};
        it.speech = clean + L", list item " + std::to_wstring(row + 1) + L" of " +
                    std::to_wstring(s.count) + (s.select == row ? L", selected" : L"");
        it.key = (uint64_t)w.ptr | ((uint64_t)(row + 1) << 32);
        items->push_back(std::move(it));
    }
}

// One item per badge on the Records > Badges tab. The game draws all 20 in
// one BadgeWidget; names and levels are read from game memory, and the
// hover probe makes the game show each badge's own progress text.
void AddBadges(const WidgetInfo& w, std::vector<Item>* items) {
    std::vector<BadgeCell> cells;
    if (!ReadBadgeGrid(w.ptr, w.absX, w.absY, &cells)) return;
    for (const BadgeCell& c : cells) {
        Item it{w.ptr, ItemKind::Badge, L"", c.centerX - Px(30), c.centerY - Px(30), Px(60), Px(60),
                c.centerX, c.centerY, false, false, L""};
        if (c.hitKnown) {
            it.absX = c.hitX;
            it.absY = c.hitY;
            it.width = c.hitWidth;
            it.height = c.hitHeight;
        }
        std::wstring name = CleanGameText(c.name);
        std::wstring level = CleanGameText(c.levelName);
        it.speech = (name.empty() ? L"unnamed badge" : name) + L", badge, " +
                    (!c.levelKnown ? std::wstring(L"level unknown")
                     : c.level == 0 ? std::wstring(L"not earned")
                     : (level.empty() ? L"level " + std::to_wstring(c.level) : level));
        it.key = (uint64_t)w.ptr | ((uint64_t)(c.id + 1) << 32);
        // The game's own badge text (title with progress, then how to earn
        // the next level), built by the badge itself.
        std::wstring title, body;
        if (c.badge && hover_text::BadgeTooltip(c.badge, &title, &body)) {
            title = CleanGameText(title);
            body = CleanGameText(body);
            it.description = title + (title.empty() || body.empty() ? L"" : L". ") + body;
        }
        items->push_back(std::move(it));
    }
}

// Rebuilds the item list for the topmost layer and announces context changes.
void Refresh() {
    uintptr_t wm = FindWidgetManager();
    if (!wm) return;
    std::vector<WidgetInfo> all = SnapshotWidgets(wm);
    std::vector<DrawnText> frame = TextCaptureLastFrame();
    g_sectionTitles.clear();  // refilled below if Zen options are showing

    // Topmost visible dialog limits navigation to its own subtree.
    int layerStart = 0, layerDepth = -1;
    for (int i = (int)all.size() - 1; i >= 0; --i) {
        if (all[i].isDialog && all[i].visible) {
            layerStart = i;
            layerDepth = all[i].depth;
            break;
        }
    }
    uintptr_t context = layerDepth >= 0 ? all[layerStart].ptr : 0;
    std::string contextClass = layerDepth >= 0 ? all[layerStart].className : "";
    // Only a modal dialog (WidgetManager mBaseModalWidget set) blocks the
    // rest of the screen. OptionsDialog is not modal: the game closes it via
    // the main menu's options orb, which it moves next to the dialog.
    uint32_t modal = 0;
    ReadU32(wm + sexy::kWmBaseModalWidget, &modal);
    bool restrictToDialog = layerDepth >= 0 && modal != 0;


    int logicalW = 0, logicalH = 0;
    if (!GetLogicalSize(wm, &logicalW, &logicalH)) return;  // unknown layout: say nothing
    g_layoutScale = logicalH / 768.0;
    // The part of logical space shown in the window (mouse remap rect).
    int visibleRect[4] = {0, 0, logicalW, logicalH};
    for (int k = 0; k < 4; ++k) {
        int32_t v;
        if (ReadI32(wm + sexy::kWmLogicalRect + 4 * k, &v)) visibleRect[k] = v;
        g_visibleRect[k] = visibleRect[k];
    }

    std::vector<Item> items;
    int topmostItem = -1;  // the item drawn last, used to name the screen
    for (int i = restrictToDialog ? layerStart + 1 : 0; i < (int)all.size(); ++i) {
        const WidgetInfo& w = all[i];
        if (restrictToDialog && w.depth <= layerDepth) break;
        if (!w.visible || w.width <= 0 || w.height <= 0) continue;
        // The window-mode toggle sits outside every screen; skip it.
        if (w.className == "WindowedButtonWidget") continue;
        if (w.isButton && LabelOnlyOffScreen(w, frame, visibleRect)) continue;
        if (zen::IsZenOptionsDialog(w.ptr)) {
            zen::ZenOptionsState zs;
            if (zen::ReadZenOptions(w.ptr, &zs)) {
                for (const zen::ZenSection& sec : zs.sections)
                    if (sec.container) g_sectionTitles.push_back({sec.container, CleanGameText(sec.title)});
                AddZenSections(zs, all, &items);
            }
        }
        if (IsBadgeWidget(w.ptr)) {
            size_t before = items.size();
            AddBadges(w, &items);
            if (items.size() > before) topmostItem = i;
            continue;
        }
        if (controls::Classify(w.ptr) == controls::Kind::List) {
            int hit = HitTest(all, w.absX + w.width / 2, w.absY + w.height / 2);
            if (hit < 0 || !IsWithin(all, hit, i)) continue;
            size_t before = items.size();
            AddListRows(w, frame, &items);
            if (items.size() > before) topmostItem = i;
            continue;
        }
        Item it;
        if (!MakeItem(w, all, frame, contextClass, &it)) continue;
        // Disabled controls are not offered, except the current tab, which
        // the game marks by disabling its button.
        if (w.disabled && !it.selectedTab) continue;
        // Skip controls covered by a screen drawn on top of them (e.g. the
        // main menu's corner buttons while the play menu is open): a click
        // at their centre would go to something else.
        // Parked off screen (e.g. the board's replay button until a game ends).
        if (it.centerX < visibleRect[0] || it.centerX >= visibleRect[0] + visibleRect[2] ||
            it.centerY < visibleRect[1] || it.centerY >= visibleRect[1] + visibleRect[3])
            continue;
        // Score rows are read-only, so click routing does not matter for them.
        int hit = HitTest(all, it.centerX, it.centerY);
        if (it.kind != ItemKind::ScoreRow && (hit < 0 || !IsWithin(all, hit, i))) continue;
        topmostItem = i;
        it.key = it.ptr;
        items.push_back(std::move(it));
    }
    if (context == 0 && topmostItem >= 0) {
        // The screen is the item's nearest full-screen ancestor (PlayMenu,
        // MainMenu, ...), or its top-level ancestor if none is full size.
        int screen = -1;
        for (int i = all[topmostItem].parentIndex; i >= 0; i = all[i].parentIndex) {
            if (all[i].width >= logicalW * 9 / 10 && all[i].height >= logicalH * 9 / 10) {
                screen = i;
                break;
            }
            if (all[i].parentIndex < 0) screen = i;
        }
        if (screen >= 0) {
            context = all[screen].ptr;
            contextClass = all[screen].className;
        }
    }
    SortReadingOrder(&items);
    g_items.swap(items);
    EchoEditChanges(wm, all);
    // In a game when the current screen is the board itself (ClassicBoard,
    // SpeedBoard, ...; all derive from Board). Panels over it, such as Zen
    // options, are screens of their own even though they are not dialogs.
    g_onBoard = context != 0 && IsKindOf(context, "Board");

    // Screens slide in and out, so the widget set is briefly a mix of old and
    // new. Announce only once the context and item set have been unchanged
    // for kSettleTicks.
    std::vector<uint64_t> signature;
    signature.push_back(context);
    for (const Item& it : g_items) signature.push_back(it.key);
    if (signature != g_pendingSignature) {
        g_pendingSignature = signature;
        g_stableTicks = 0;
    } else if (g_stableTicks < kSettleTicks) {
        ++g_stableTicks;
    }
    bool settled = g_stableTicks >= kSettleTicks;

    if (settled && context != g_context) {
        g_context = context;
        g_contextClass = contextClass;
        g_focus = 0;
        g_lastHover = 0;
        if (!context) return;
        std::wstring text = layerDepth >= 0 ? DialogSpeech(all, layerStart) : L"";
        if (text.empty()) {
            // The game's own name for the screen where it has one: a board's
            // mode or quest title from its parameters (docs/re/
            // screen-names-and-keys.md). The class->string-id table there is
            // not used (no hard-coded names); other screens keep their class
            // name.
            std::wstring name;
            ScreenNameSource source = ScreenNameSource::None;
            if (ScreenNameWithSource(context, false, &name, &source) &&
                (source == ScreenNameSource::BoardTitleText ||
                 source == ScreenNameSource::BoardTitle ||
                 source == ScreenNameSource::DrawnHeading || source == ScreenNameSource::DialogHeader)) {
                text = CleanGameText(name);
                if (IsKindOf(context, "Board")) text += L", game";
            }
        }
        if (text.empty()) text = FriendlyClassName(contextClass);
        std::wstring section;
        if (ScreenSection(context, &section) && !CleanGameText(section).empty())
            text += L", " + CleanGameText(section);
        g_contextSpeech = text;
        Log("nav: context %s %08X, %d items", contextClass.c_str(), context,
            (int)g_items.size());
        Speak(text, true);
        // Start on the item under the game's mouse (the button just used
        // to come back here), else the game's own keyboard focus.
        for (const Item& it : g_items)
            if (it.isOver && !g_focus) g_focus = g_lastHover = it.key;
        uintptr_t gameFocus = GameFocusWidget(wm);
        for (const Item& it : g_items)
            if (!g_focus && it.ptr == gameFocus) g_focus = it.key;
        if (!g_focus && !g_items.empty()) g_focus = g_items[0].key;
        SpeakFocus(false);
        g_announcedCount = g_items.size();
        return;
    }

    // Items that arrive after the screen was announced (the main menu's
    // orbs fly in one after another): say the new count once.
    // Reported once the count has stopped growing for a second, so the
    // main menu's fly-in gives one "6 items" instead of one per orb.
    if (context == g_context) {
        static size_t lastSeen = 0;
        if (g_items.size() != lastSeen) {
            lastSeen = g_items.size();
            g_growthQuietTicks = 0;
        } else if (g_growthQuietTicks < 20) {
            ++g_growthQuietTicks;
        }
        if (g_growthQuietTicks >= 20) {
            if (g_items.size() > g_announcedCount && !g_onBoard)  // board buttons come and go
                Speak(std::to_wstring(g_items.size()) + L" items", false);
            g_announcedCount = g_items.size();
        }
    }

    // The focused item went away within the same screen. Prefer the item of
    // an ancestor widget (a closed drop-down list's row -> the drop-down),
    // else the first item, and say it.
    if (settled && context == g_context && g_focus && FocusIndex() < 0) {
        uint64_t next = g_items.empty() ? 0 : g_items[0].key;
        int lost = -1;
        for (int k = 0; k < (int)all.size(); ++k)
            if (all[k].ptr == g_focusWidget) lost = k;
        for (int k = lost >= 0 ? all[lost].parentIndex : -1; k >= 0; k = all[k].parentIndex) {
            bool found = false;
            for (const Item& it : g_items)
                if (it.key == all[k].ptr) {
                    next = it.key;
                    found = true;
                }
            if (found) break;
        }
        g_focus = next;
        // On a board the buttons come and go (the hint button greys out after
        // use); the board speech owns the voice there, so move focus quietly.
        if (!g_onBoard) SpeakFocus(true);
    }
    if (const Item* f = FocusedItem()) g_focusWidget = f->ptr;

    // A real mouse (e.g. a sighted helper) moves focus too. Hover the mod or
    // the game's own bookkeeping causes is not followed.
    if (g_actions.empty() && GetTickCount() - g_realMouseTime < 1000) {
        for (const Item& it : g_items) {
            if (it.isOver && it.key != g_lastHover) {
                g_lastHover = it.key;
                if (it.key != g_focus) {
                    g_focus = it.key;
                    SpeakFocus(true);
                }
            }
        }
    }
}

bool CorrectSlider();

// Posts at most one queued mouse event per tick.
void ProcessActions(HWND hwnd) {
    if (g_actions.empty()) {
        if (g_reportTicks > 0 && --g_reportTicks == 0) {
            // Re-read state after the game handled the input, then say it.
            g_reportTicks = -1;
            if (!CorrectSlider()) SpeakFocus(true);
        }
        return;
    }
    MouseAction& a = g_actions.front();
    if (a.waitHover) {
        uint8_t over = 0;
        bool readable = ReadU8(a.waitHover + sexy::kIsOver, &over);
        if (!(readable && over)) {
            if (++g_hoverWaitTicks > 10) {
                Log("nav: target %08X never reported hover (readable=%d)", a.waitHover,
                    readable);
                Speak(L"Could not reach that control", true);
                if (g_buttonHeld)
                    PostMessageW(hwnd, WM_LBUTTONUP, 0, MAKELPARAM(a.clientX, a.clientY));
                g_buttonHeld = false;
                g_actions.clear();
                g_reportTicks = -1;
            }
            return;
        }
        g_hoverWaitTicks = 0;
        g_actions.pop_front();
        return;
    }
    LPARAM pos = MAKELPARAM(a.clientX, a.clientY);
    switch (a.type) {
        case controls::MouseStep::Move:
            PostMouseMove(hwnd, g_buttonHeld ? MK_LBUTTON : 0, pos);
            break;
        case controls::MouseStep::Down:
            PostMessageW(hwnd, WM_LBUTTONDOWN, MK_LBUTTON, pos);
            g_buttonHeld = true;
            break;
        case controls::MouseStep::Up:
            PostMessageW(hwnd, WM_LBUTTONUP, 0, pos);
            g_buttonHeld = false;
            Log("nav: mouse up at client %d,%d", a.clientX, a.clientY);
            break;
    }
    g_actions.pop_front();
}

// Queues a planned mouse sequence. A Move that must reach a widget is
// followed by a wait for that widget's hover flag, which also proves the
// coordinate mapping is right.
bool QueueSteps(const std::vector<controls::MouseStep>& steps) {
    uintptr_t wm = FindWidgetManager();
    if (!wm || steps.empty()) return false;
    std::deque<MouseAction> queue;
    for (const controls::MouseStep& s : steps) {
        int cx, cy;
        if (!controls::LogicalToClientCentre(wm, s.x, s.y, &cx, &cy)) return false;
        queue.push_back({s.type, cx, cy, 0});
        if (s.type == controls::MouseStep::Move && s.waitHover)
            queue.push_back({s.type, cx, cy, s.waitHover});
    }
    g_actions = std::move(queue);
    g_hoverWaitTicks = 0;
    return true;
}

void Activate() {
    const Item* item = FocusedItem();
    if (!item || !g_actions.empty()) return;
    if (item->kind == ItemKind::Tab && item->selectedTab) {
        Speak(L"Already selected", true);
        return;
    }
    if (item->kind == ItemKind::Slider) {
        Speak(L"Use left and right arrows to change", true);
        return;
    }
    if (item->kind == ItemKind::ScoreRow || item->kind == ItemKind::Badge) {
        SpeakFocus(true);
        return;
    }
    // Operate the control through the game's own code, the same functions
    // its input handling ends in (docs/re/game-actions.md): no mouse, window
    // or screen involved.
    bool done = false;
    int row = (int)(item->key >> 32) - 1;  // list rows carry their row number
    switch (item->kind) {
        case ItemKind::Button:
        case ItemKind::Tab:
            done = game_actions::PressButton(item->ptr);
            break;
        case ItemKind::Checkbox:
            done = game_actions::ClickCheckbox(item->ptr);
            break;
        case ItemKind::DropList:
            done = game_actions::ToggleDropList(item->ptr);
            break;
        case ItemKind::ListRow: {
            uint32_t parent = 0;
            ReadU32(item->ptr + sexy::kParent, &parent);
            if (parent && controls::Classify(parent) == controls::Kind::DropList)
                done = game_actions::ChooseDropListRow(parent, row);
            else
                done = game_actions::ChooseListRow(item->ptr, row);
            break;
        }
        case ItemKind::Section: {
            uint32_t dialog = 0;
            int32_t id = -1;
            bool blocked = false;
            if (ReadU32(item->ptr + zen::off::kSecDialog, &dialog) &&
                ReadI32(item->ptr + zen::off::kSecId, &id) &&
                game_actions::ZenSectionSelectBlocked(dialog, &blocked) && blocked) {
                Speak(L"Close the open list first", true);
                return;
            }
            done = dialog && id >= 0 && game_actions::SelectZenSection(dialog, id);
            break;
        }
        default:
            break;
    }
    if (!done) {
        // Edit fields, and anything the direct call refused: a plain click
        // through the game's mouse handling.
        Log("nav: no direct action for %08X (kind %d); using a click", item->ptr, (int)item->kind);
        std::vector<controls::MouseStep> steps = controls::PlanCheckboxToggle(
            item->ptr, item->absX, item->absY, item->width, item->height);
        if (!QueueSteps(steps)) {
            Speak(L"Could not locate that control", true);
            return;
        }
    }
    // Checkboxes and tabs stay on screen, so report their new state.
    if (item->kind == ItemKind::Checkbox || item->kind == ItemKind::Tab ||
        item->kind == ItemKind::ListRow || item->kind == ItemKind::DropList ||
        item->kind == ItemKind::Section)
        g_reportTicks = 4;
    g_change.ptr = g_context;
    g_change.ticksLeft = 12;  // 600 ms: page switch animations
    g_change.beforeFragments.clear();
    for (const DrawnText& t : TextCaptureLastFrame())
        if (Visible(t)) g_change.beforeFragments.push_back(t);
    g_change.before = ReadingOrder(g_change.beforeFragments);
}

// A slider move in progress: the value asked for, checked after the game
// handled the mouse, with up to two correcting moves (the mouse lands on
// whole pixels, so one move can miss by a step of the slider's resolution).
struct SliderGoal {
    uintptr_t ptr = 0;
    double target = 0;
    int corrections = 0;
};
SliderGoal g_sliderGoal;

bool MoveSliderTo(const Item& item, const controls::SliderState& s, double target) {
    std::vector<controls::MouseStep> steps;
    double predicted = 0;
    if (!controls::PlanSliderSet(item.ptr, s, item.absX, item.absY, target, &steps, &predicted) ||
        !QueueSteps(steps))
        return false;
    Log("nav: slider %08X %.3f -> target %.3f predicted %.3f", item.ptr, s.value, target,
        predicted);
    g_reportTicks = 4;
    return true;
}

void AdjustSlider(int direction) {
    const Item* item = FocusedItem();
    controls::SliderState s;
    if (!item || !g_actions.empty() || !controls::ReadSlider(item->ptr, &s)) return;
    // Steps of 10 % of what is shown. Right means more; on a vertical slider
    // more is up, which is a lower value.
    double shown = s.horizontal ? s.value : 1.0 - s.value;
    double nextShown = std::floor(shown * 10.0 + 0.5) / 10.0 + 0.1 * direction;
    nextShown = std::min(1.0, std::max(0.0, nextShown));
    double target = s.horizontal ? nextShown : 1.0 - nextShown;
    if (std::abs(target - s.value) < 0.001) {
        SpeakFocus(true);
        return;
    }
    // Set the value through the game's own slider code (SetValue, then the
    // release handler that notifies the settings and plays the preview).
    if (game_actions::SetSlider(item->ptr, target)) {
        g_reportTicks = 2;
        return;
    }
    Log("nav: direct slider set refused for %08X; dragging", item->ptr);
    g_sliderGoal = {item->ptr, target, 0};
    if (!MoveSliderTo(*item, s, target)) {
        g_sliderGoal.ptr = 0;
        Speak(L"Could not change that slider", true);
    }
}

// Called when a slider move has been handled. Returns true if another,
// correcting move was queued (the report then waits for it).
bool CorrectSlider() {
    const Item* item = FocusedItem();
    controls::SliderState s;
    if (!g_sliderGoal.ptr || !item || item->ptr != g_sliderGoal.ptr ||
        !controls::ReadSlider(item->ptr, &s)) {
        g_sliderGoal.ptr = 0;
        return false;
    }
    double miss = g_sliderGoal.target - s.value;
    if (std::abs(miss) <= 0.004 || g_sliderGoal.corrections >= 2) {
        g_sliderGoal.ptr = 0;
        return false;
    }
    ++g_sliderGoal.corrections;
    double aim = std::min(1.0, std::max(0.0, g_sliderGoal.target + miss));
    return MoveSliderTo(*item, s, aim);
}

// Visible drawn text joined into rows: fragments whose baselines are within
// 4 px form one row, ordered left to right (descriptions are drawn as
// several coloured fragments per line).
struct TextRow {
    std::wstring text;
    int y;
};
std::vector<TextRow> VisibleRows();

std::vector<std::wstring> VisibleStrings() {
    std::vector<std::wstring> out;
    for (const TextRow& r : VisibleRows()) out.push_back(r.text);
    return out;
}

std::vector<TextRow> VisibleRows() {
    std::vector<DrawnText> frame;
    for (const DrawnText& t : TextCaptureLastFrame())
        if (Visible(t)) frame.push_back(t);
    std::stable_sort(frame.begin(), frame.end(), [](const DrawnText& a, const DrawnText& b) {
        if (std::abs(a.y - b.y) > Px(4)) return a.y < b.y;
        return a.x < b.x;
    });
    std::vector<TextRow> rows;
    int rowY = 0;
    for (size_t i = 0; i < frame.size(); ++i) {
        if (i == 0 || std::abs(frame[i].y - rowY) > Px(4)) {
            rowY = frame[i].y;
            rows.push_back({L"", rowY});
        }
        std::wstring& row = rows.back().text;
        const std::wstring& piece = frame[i].text;
        // Separate side-by-side captions; colour fragments of one sentence
        // already carry their own spaces.
        if (!row.empty() && !piece.empty() && row.back() != L' ' && piece[0] != L' ')
            row += L' ';
        row += piece;
    }
    for (TextRow& r : rows) r.text = CleanGameText(r.text);
    return rows;
}

void StartHoverProbe(HWND hwnd) {
    const Item* item = FocusedItem();
    uintptr_t wm = FindWidgetManager();
    if (!item || !wm || g_onBoard || !g_actions.empty()) return;
    g_hover.ptr = item->ptr;
    g_hover.ticksLeft = 5;  // 250 ms for the game to react and draw
    if (item->kind == ItemKind::Section) g_hover.ticksLeft = 14;  // section opening animation
    if (item->kind == ItemKind::Badge) g_hover.ticksLeft = 9;  // tooltip fades in
    g_hover.before = VisibleStrings();
    // Do what the game does for a mouse user, through its own code: a Zen
    // section opens (is selected) when hovered; other controls get the
    // game's hover change (mouse enter/leave and listener notification).
    // Badges and quests already carry their text, so they need nothing.
    (void)hwnd;
    if (item->kind == ItemKind::Badge || !item->description.empty() && item->kind != ItemKind::Section) {
        g_hover.ptr = 0;
        return;
    }
    if (item->kind == ItemKind::Section) {
        uint32_t dialog = 0;
        int32_t id = -1;
        bool blocked = true;
        if (ReadU32(item->ptr + zen::off::kSecDialog, &dialog) &&
            ReadI32(item->ptr + zen::off::kSecId, &id) &&
            game_actions::ZenSectionSelectBlocked(dialog, &blocked) && !blocked)
            game_actions::SelectZenSection(dialog, id);
        g_hover.ptr = 0;  // its description is already spoken with it
        return;
    }
    game_actions::HoverWidget(item->ptr, true);
}

void FinishHoverProbe() {
    if (!g_hover.ptr || --g_hover.ticksLeft > 0) return;
    uintptr_t probed = g_hover.ptr;
    g_hover.ptr = 0;
    const Item* item = FocusedItem();
    if (!item || item->ptr != probed) return;  // focus moved on meanwhile
    // The play menu writes the hovered mode's description into its own
    // field when the game's hover notification runs; locked modes get the
    // heading the game draws above it (string 352).
    std::wstring description;
    bool locked = false;
    if (g_contextClass == "PlayMenu" &&
        hover_text::PlayMenuDescription(g_context, &description, &locked)) {
        description = CleanGameText(description);
        std::wstring heading;
        if (locked && GameString(352, &heading)) description = CleanGameText(heading) + L". " + description;
        if (!description.empty()) Speak(description, false);
        return;
    }
    // A changed row brings its whole text block (rows less than 25 px apart)
    // with it: consecutive quest descriptions can share their first lines.
    std::vector<TextRow> rows = VisibleRows();
    std::vector<bool> take(rows.size(), false);
    for (size_t i = 0; i < rows.size(); ++i) {
        const std::wstring& s = rows[i].text;
        if (s.empty() || item->speech.find(s) != std::wstring::npos) continue;
        if (std::find(g_hover.before.begin(), g_hover.before.end(), s) == g_hover.before.end())
            take[i] = true;
    }
    for (bool grew = true; grew;) {
        grew = false;
        for (size_t i = 0; i < rows.size(); ++i) {
            if (take[i]) continue;
            bool nearTaken = (i > 0 && take[i - 1] && rows[i].y - rows[i - 1].y < Px(25)) ||
                             (i + 1 < rows.size() && take[i + 1] && rows[i + 1].y - rows[i].y < Px(25));
            if (nearTaken && !rows[i].text.empty() &&
                item->speech.find(rows[i].text) == std::wstring::npos) {
                take[i] = true;
                grew = true;
            }
        }
    }
    std::wstring added;
    for (size_t i = 0; i < rows.size(); ++i)
        if (take[i] && added.find(rows[i].text) == std::wstring::npos)
            added += (added.empty() ? L"" : L" ") + rows[i].text;
    if (!added.empty()) Speak(added, false);
}

// Speaks rows of text that appeared after a press, if the screen stayed the
// same (a new screen or dialog is announced by Refresh instead).
void FinishChangeProbe() {
    if (!g_change.ptr || --g_change.ticksLeft > 0) return;
    uintptr_t screen = g_change.ptr;
    g_change.ptr = 0;
    // A new screen or dialog (even one still settling) is announced by
    // Refresh; only report changes within the same, settled screen.
    if (screen != g_context || g_pendingSignature.empty() ||
        g_pendingSignature[0] != g_context || g_stableTicks < kSettleTicks)
        return;
    // Whole pieces (table rows, captions) in table-aware order that were not
    // on screen before the press: a changed score row is read complete.
    std::vector<DrawnText> now;
    for (const DrawnText& t : TextCaptureLastFrame())
        if (Visible(t)) now.push_back(t);
    std::wstring added;
    for (const std::wstring& piece : ReadingOrder(now)) {
        if (piece.empty() || added.find(piece) != std::wstring::npos) continue;
        if (std::find(g_change.before.begin(), g_change.before.end(), piece) !=
            g_change.before.end())
            continue;
        bool isItem = false;
        for (const Item& it : g_items)
            if (it.speech.find(piece) != std::wstring::npos) isItem = true;
        if (isItem) continue;
        added += (added.empty() ? L"" : L". ") + piece;
    }
    if (!added.empty()) Speak(added, false);
}

void MoveFocus(HWND hwnd, int delta) {
    if (g_items.empty()) {
        Speak(L"No buttons", true);
        return;
    }
    int i = FocusIndex();
    int n = (int)g_items.size();
    i = i < 0 ? (delta > 0 ? 0 : n - 1) : (i + delta + n) % n;
    g_focus = g_items[i].key;
    SpeakFocus(true);
    StartHoverProbe(hwnd);
}

// Marks the character message that TranslateMessage generates for a
// consumed key, so the game's edit field does not also receive it.
bool Consume(WPARAM key) {
    g_swallowChar = key == VK_SPACE ? L' ' : key == VK_RETURN ? L'\r' : key == VK_TAB ? L'\t' : 0;
    return true;
}

