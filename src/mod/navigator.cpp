// Spoken game status for the status key: only values that were read.
void SpeakHud() {
    HudState s;
    if (!ReadHud(&s) || !s.board) {
        Speak(L"Not in a game", true);
        return;
    }
    std::wstring out;
    auto add = [&](const wchar_t* name, const HudInt& v) {
        if (!v.known) return;
        out += (out.empty() ? L"" : L", ") + std::wstring(name) + L" " + std::to_wstring(v.value);
    };
    add(L"score", s.score);
    add(L"level", s.level);
    if (s.levelTarget.known && s.levelTarget.value > 0 && s.levelPoints.known)
        out += L", progress " + std::to_wstring(s.levelPoints.value) + L" of " +
               std::to_wstring(s.levelTarget.value);
    if (s.multiplier.known && s.multiplier.value > 1)
        out += L", multiplier " + std::to_wstring(s.multiplier.value);
    if (s.ticksLeft.known && s.timeLimitSeconds.known && s.timeLimitSeconds.value > 0) {
        out += L", time " + HudTimeText(s.ticksLeft.value);
    }
    add(L"moves left", s.movesLeft);
    if (s.questDescriptionKnown && !s.questDescription.empty())
        out += L". " + CleanGameText(s.questDescription);
    Speak(out.empty() ? L"Game status unknown" : out, true);
    Log("nav: hud %s", HudDescribe(s).c_str());
}

// Badge award dialogs step through several badges; quest mode completion
// is announced on the quest menu. Both change without a new screen.
void PollRareChanges() {
    static int lastShown = -2;
    static std::wstring lastQuestNote;
    if (dialog_text::ClassifyRareDialog(g_context) == dialog_text::RareDialog::BadgeAward) {
        dialog_text::BadgeAwardInfo b;
        if (dialog_text::ReadBadgeAward(g_context, &b) && b.indexKnown && b.shownIndex != lastShown) {
            if (lastShown != -2 && b.shownIndex >= 0 && b.shownIndex < (int)b.badges.size()) {
                const dialog_text::AwardedBadge& a = b.badges[b.shownIndex];
                Speak(CleanGameText(a.name) + L", " + CleanGameText(a.levelName), false);
            }
            lastShown = b.shownIndex;
        }
    } else {
        lastShown = -2;
    }
    std::wstring note;
    if (g_contextClass == "QuestMenu" && dialog_text::ReadQuestMenuAnnouncement(g_context, &note)) {
        note = CleanGameText(note);
        if (note != lastQuestNote && !note.empty()) Speak(note, false);
        lastQuestNote = note;
    } else {
        lastQuestNote.clear();
    }
}

void NavigatorTick(HWND hwnd) {
    PollRareChanges();
    if (g_onBoard) BoardTick(g_context);
    else BoardReset();
    static bool loggedStrings = false;
    if (!loggedStrings && FindWidgetManager()) {
        loggedStrings = true;
        Log("nav: game string table has %d entries", GameStringCount());
    }
    SpeakAnnouncements();
    Refresh();
    ProcessActions(hwnd);
    FinishHoverProbe();
    FinishChangeProbe();
}

bool NavigatorKeyDown(HWND hwnd, WPARAM key) {
    g_swallowChar = 0;
    bool shift = (GetKeyState(VK_SHIFT) & 0x8000) != 0;
    switch (key) {
        case VK_F12:
            if (uintptr_t wm = FindWidgetManager()) {
                DumpWidgetTree(wm);
                for (const WidgetInfo& w : SnapshotWidgets(wm))
                    if (w.visible && IsBadgeWidget(w.ptr)) DumpBadgeGrid(w.ptr, w.absX, w.absY);
            }
            TextCaptureDumpLastFrame();
            if (g_context && dialog_text::ClassifyRareDialog(g_context) != dialog_text::RareDialog::None)
                dialog_text::DumpRareDialog(g_context);
            {
                HudState hud;
                if (ReadHud(&hud) && hud.board) Log("dump: hud %s", HudDescribe(hud).c_str());
            }
            Speak(L"Widget tree written to log", true);
            return true;
        case VK_F5:
            Speak(g_contextSpeech.empty() ? L"No menu" : g_contextSpeech, true);
            SpeakFocus(false);
            return true;
        case VK_F6:
            SpeakHud();
            return true;
    }
    // The mod's board reading keys (E, Q, ...); the game's own keys pass on.
    if (g_onBoard && BoardKeyDown(g_context, key)) {
        g_swallowChar = (key >= 'A' && key <= 'Z') ? (WPARAM)(key - 'A' + 'a') : 0;
        return true;
    }
    if (g_items.empty()) return false;  // leave keys to the game outside menus
    const Item* item = FocusedItem();
    bool onEdit = item && item->kind == ItemKind::Edit;
    bool onSlider = item && item->kind == ItemKind::Slider;

    // During play the game's own keyboard controls own the arrows, W/A/S/D,
    // Space and Enter (readme: arrows move the gem reticle, WASD swap). The
    // board's buttons stay reachable with Tab, and Enter presses one only
    // right after Tab has moved to it.
    if (g_onBoard) {
        if (key == VK_TAB) {
            MoveFocus(hwnd, shift ? -1 : 1);
            g_boardButtonArmed = true;
            return Consume(key);
        }
        if (key == VK_RETURN && g_boardButtonArmed) {
            g_boardButtonArmed = false;
            Activate();
            return Consume(key);
        }
        g_boardButtonArmed = false;
        return false;
    }

    switch (key) {
        case VK_DOWN: MoveFocus(hwnd, 1); return true;
        case VK_UP: MoveFocus(hwnd, -1); return true;
        case VK_TAB: MoveFocus(hwnd, shift ? -1 : 1); return Consume(key);
        case VK_LEFT: if (!onSlider) return false; AdjustSlider(-1); return true;
        case VK_RIGHT: if (!onSlider) return false; AdjustSlider(1); return true;
        case VK_HOME: if (onEdit) return false; g_focus = 0; MoveFocus(hwnd, 1); return true;
        case VK_END: if (onEdit) return false; g_focus = 0; MoveFocus(hwnd, -1); return true;
        case VK_SPACE:
            if (onEdit) return false;  // typing a space into the field
            Activate();
            return Consume(key);
        case VK_RETURN:
            // On an edit field Enter belongs to the game (it may submit).
            if (onEdit) return false;
            Activate();
            return Consume(key);
    }
    return false;
}

bool NavigatorChar(WPARAM ch) {
    if (g_swallowChar && ch == g_swallowChar) {
        g_swallowChar = 0;
        return true;
    }
    return false;
}

