// The mod moves the game's mouse with posted messages. When the real cursor
// is outside the game window (windowed mode), Windows then reports
// WM_MOUSELEAVE and the game drops the hover the mod just set. While the
// mouse position is the one the mod last posted, the mod owns the mouse and
// those leave messages are withheld; any other position is the real mouse.
bool g_modOwnsMouse = false;
LPARAM g_lastPostedPos = 0;
DWORD g_realMouseTime = 0;  // last WM_MOUSEMOVE the mod did not post

void PostMouseMove(HWND hwnd, WPARAM flags, LPARAM pos) {
    g_modOwnsMouse = true;
    g_lastPostedPos = pos;
    MouseOverrideSet(hwnd, POINT{(short)LOWORD(pos), (short)HIWORD(pos)});
    PostMessageW(hwnd, WM_MOUSEMOVE, flags, pos);
}

