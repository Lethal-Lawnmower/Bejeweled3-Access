"""Generate the winmm.dll proxy export table from the system's 32-bit winmm.dll.

Usage: python -I gen_winmm_proxy.py C:\\Windows\\SysWOW64\\winmm.dll src\\proxy

Writes:
  winmm_exports.def   module-definition file (named exports, original ordinals)
  winmm_stubs.inc     X-macro list: WINMM_EXPORT(index, name)

The proxy cannot use export forwarders (they cannot name the real DLL by full
path), so each export is a naked jump through a table filled at load time.
"""
import os
import struct
import sys


def exports(path):
    data = open(path, "rb").read()
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    nsec = struct.unpack_from("<H", data, pe + 6)[0]
    optsize = struct.unpack_from("<H", data, pe + 20)[0]
    opt = pe + 24
    export_rva = struct.unpack_from("<I", data, opt + 96)[0]
    secs = []
    off = opt + optsize
    for _ in range(nsec):
        vsize, va, rsize, raw = struct.unpack_from("<IIII", data, off + 8)
        secs.append((va, max(vsize, rsize), raw))
        off += 40

    def r2o(rva):
        for va, size, raw in secs:
            if va <= rva < va + size:
                return raw + rva - va
        raise ValueError(hex(rva))

    e = r2o(export_rva)
    base, nfuncs, nnames, afuncs, anames, aords = struct.unpack_from("<IIIIII", data, e + 16)
    out = []
    for i in range(nnames):
        name_rva = struct.unpack_from("<I", data, r2o(anames) + 4 * i)[0]
        o = r2o(name_rva)
        name = data[o:data.index(b"\0", o)].decode()
        ordinal = base + struct.unpack_from("<H", data, r2o(aords) + 2 * i)[0]
        out.append((name, ordinal))
    return sorted(out, key=lambda t: t[1])


def main():
    src, outdir = sys.argv[1], sys.argv[2]
    names = exports(src)
    os.makedirs(outdir, exist_ok=True)
    with open(os.path.join(outdir, "winmm_exports.def"), "w", newline="\n") as f:
        f.write("; Generated by tools/gen_winmm_proxy.py. Do not edit.\n")
        f.write("LIBRARY winmm\nEXPORTS\n")
        for i, (name, ordinal) in enumerate(names):
            f.write(f"    {name}=Proxy_{name} @{ordinal}\n")
    with open(os.path.join(outdir, "winmm_stubs.inc"), "w", newline="\n") as f:
        f.write("// Generated by tools/gen_winmm_proxy.py. Do not edit.\n")
        for i, (name, ordinal) in enumerate(names):
            f.write(f"WINMM_EXPORT({i}, {name})\n")
    print(f"{len(names)} exports")


main()
